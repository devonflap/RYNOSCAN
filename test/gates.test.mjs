import { gateReport } from '../src/gates.mjs';
import { compact, appendHistory } from '../src/funnel.mjs';
import { compose } from '../src/weekly.mjs';
let f=0;const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)f=1;};
const mk=(n,miss,R)=>Array.from({length:n},(_,i)=>({setup:'Bottom reversal',miss,resultR:R+(i%3-1)*0.1,status:'stopped out'}));
const hist=[{t:'2026-10-10T00:00:00Z',rn:10,bn:5,ready:0,one:2,r:{zone:[8,3],volume:[2,0]},b:{room:[1,0]}}];
let g=gateReport([...mk(10,'',1),...mk(10,'zone',-0.8)],hist);
const z=g.reversal.find(r=>r.gate==='zone');
ok(z.verdict==='keep','gate whose early trades do worse is kept');
ok(z.failPct===80,'bottleneck fail percent from history');
g=gateReport([...mk(10,'',-0.5),...mk(10,'zone',0.9)],hist);
ok(g.reversal.find(r=>r.gate==='zone').verdict==='relax','gate whose early trades do better is flagged to relax');
g=gateReport(mk(3,'',1),hist);
ok(g.reversal.every(r=>r.verdict==='unclear'),'too little data stays unclear');
ok(g.summary.some(s=>/bottleneck/.test(s)),'summary names the bottleneck');
const h=appendHistory([{t:'2020-01-01T00:00:00Z'}],{t:new Date().toISOString()},Date.now(),14);
ok(h.length===1,'old history trimmed');
ok(compose({gates:g}).body.includes('Report only'),'weekly message composed');
ok(compose(null)===null,'weekly handles no data');
{ const m=(n,miss,R,st)=>Array.from({length:n},(_,i)=>({setup:'Bottom reversal',miss,conf:'confirmed',resultR:R+(i%3-1)*0.1,status:st}));
  let q=gateReport([...m(10,'',0.8,'hit TP3'),...m(10,'zone',-0.7,'stopped out')],[]);
  ok(q.filter.verdict==='works'&&q.filter.rejected.stopPct===100,'filter audit: rejected coins did worse');
  q=gateReport([...m(10,'',-0.5,'stopped out'),...m(10,'zone',0.8,'hit TP3')],[]);
  ok(q.filter.verdict==='backwards','filter audit flags a filter rejecting winners');
  ok(gateReport([],[]).filter.verdict==='unclear','filter audit needs data'); }
process.exit(f);
